#!/usr/bin/env python3
"""Scans public/sprites/<character>/ and public/backgrounds/ and writes src/sprites-manifest.js.
Run it after adding sprites (start.bat / start.sh already do this for you)."""
import json, os, re, time, urllib.parse
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPR = os.path.join(ROOT, "public", "sprites")
EXT = (".png", ".webp", ".jpg", ".jpeg", ".gif")
out = []
for char in sorted(os.listdir(SPR)):
    d = os.path.join(SPR, char)
    if not os.path.isdir(d): continue
    for f in sorted(os.listdir(d)):
        if f.lower().endswith(EXT) and not f.startswith((".", "_")):
            label = os.path.splitext(f)[0].replace("_", " ").replace("-", " ").strip()
            out.append({"char": char, "label": label[:1].upper() + label[1:],
                        "src": "public/sprites/" + urllib.parse.quote(char) + "/" + urllib.parse.quote(f)})
BG = os.path.join(ROOT, "public", "backgrounds")
bgs = []
for dp, dn, fn in os.walk(BG):
    dn.sort()
    for f in sorted(fn):
        if f.lower().endswith(EXT) and not f.startswith((".", "_")):
            rel = os.path.relpath(os.path.join(dp, f), BG).replace(os.sep, "/")
            label = os.path.splitext(rel)[0].replace("_", " ").replace("-", " ").replace("/", " / ").strip()
            bgs.append({"label": label[:1].upper() + label[1:], "src": "public/backgrounds/" + "/".join(urllib.parse.quote(x) for x in rel.split("/"))})
with open(os.path.join(ROOT, "src", "sprites-manifest.js"), "w", encoding="utf-8") as fh:
    fh.write("/* generated by tools/make-manifest.py - do not edit */\nwindow.TWST_SPRITES = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\nwindow.TWST_BACKGROUNDS = " + json.dumps(bgs, indent=1, ensure_ascii=False) + ";\n")
# cache-bust the manifest so hosts/browsers never serve a stale list
ip = os.path.join(ROOT, "index.html")
html = open(ip, encoding="utf-8").read()
html = re.sub(r'src/sprites-manifest\.js(\?v=\d+)?', "src/sprites-manifest.js?v=" + str(int(time.time())), html)
open(ip, "w", encoding="utf-8").write(html)
print("Found", len(bgs), "background(s),", len(out), "sprites in", len({o["char"] for o in out}), "character folder(s)")
